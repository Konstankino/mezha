//! What loads into Claude's context in this project, file by file: agents,
//! skills (every file in a skill's directory, not only `SKILL.md`), rules
//! and commands, each with a fingerprint and a scan result. It is the
//! inventory OWASP AST09 asks for, and the scan behind the `bodies` check
//! (AST08). A file the scan can't read as text is `incomplete`, never
//! clean.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use mezha_memory::scan::{self, EXTERNAL_REFERENCE, Level, UNSCANNED};
use mezha_render::state::fingerprint;
use serde::Serialize;
use serde_json::Value;

use crate::ctx::Ctx;
use crate::layers::Layers;

/// The walk stops after this many files, and says so.
pub const MAX_FILES: usize = 2000;
/// Directories deeper than this aren't entered.
const MAX_DEPTH: usize = 8;
/// Files bigger than this aren't scanned.
const MAX_BYTES: u64 = 1024 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Source {
    Project,
    User,
    Plugin,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum ItemKind {
    Agent,
    Skill,
    /// Any other file in a skill's directory.
    SkillFile,
    Rule,
    Command,
}

/// The scan result for one file. Ordered from best to worst.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Coverage {
    Pass,
    Incomplete,
    Fail,
}

#[derive(Debug, Clone, Serialize)]
pub struct Item {
    pub source: Source,
    /// The plugin a plugin file comes from, as `name@marketplace`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub plugin: Option<String>,
    pub kind: ItemKind,
    /// The agent, skill, rule or command name (the skill's, for its files).
    pub name: String,
    /// Relative to the project root, or under `~/`.
    pub path: String,
    /// Generated by mezha from `mezha.toml`.
    pub managed: bool,
    /// `sha256:<hex>`, of the text with LF line endings when it is text.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub sha256: Option<String>,
    pub scan: Coverage,
    /// What failed the scan, or why it is incomplete.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub findings: Vec<String>,
    /// Phrases that read like instructions to a model.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub phrases: Vec<String>,
    /// Hosts the file links to (AST05: content that can change after review).
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub links: Vec<String>,
}

impl Item {
    /// Whether Claude Code runs `` !`cmd` `` in this file when it loads.
    fn runs_at_load(&self) -> bool {
        matches!(self.kind, ItemKind::Skill | ItemKind::Command)
    }
}

#[derive(Debug, Clone, Default)]
pub struct Inventory {
    pub items: Vec<Item>,
    /// The walk hit [`MAX_FILES`] before it finished.
    pub truncated: bool,
    /// Enabled plugins verify couldn't find on disk, as `name@marketplace`.
    pub missing_plugins: Vec<String>,
}

impl Inventory {
    /// Adds what loads from outside the repository: the user's own agents,
    /// skills, rules and commands, and those of every enabled plugin.
    pub fn walk_outside(&mut self, ctx: &Ctx, layers: &Layers) {
        let none = BTreeMap::new();
        let (config, shown) = match ctx.var("CLAUDE_CONFIG_DIR") {
            Some(dir) => (PathBuf::from(dir), dir.trim_end_matches('/').to_string()),
            None => match &ctx.home {
                Some(home) => (home.join(".claude"), "~/.claude".to_string()),
                None => return,
            },
        };
        let project = std::fs::canonicalize(ctx.root.join(".claude")).ok();
        if std::fs::canonicalize(&config).ok() != project || project.is_none() {
            self.walk(&config, &shown, Source::User, None, &none);
        }
        let plugins = ctx
            .var("CLAUDE_CODE_PLUGIN_CACHE_DIR")
            .map(PathBuf::from)
            .unwrap_or_else(|| config.join("plugins"));
        for id in enabled_plugins(layers) {
            match plugin_dir(&plugins, &id) {
                Some(dir) => {
                    let shown = format!("plugin:{id}");
                    self.walk(&dir, &shown, Source::Plugin, Some(&id), &none);
                }
                None => self.missing_plugins.push(id),
            }
        }
    }

    /// Adds the agents, skills, rules and commands under `base` (a `.claude`
    /// directory, or a plugin's root), shown as `shown/...`. `managed` holds
    /// the files mezha generates, by path under the project.
    pub fn walk(
        &mut self,
        base: &Path,
        shown: &str,
        source: Source,
        plugin: Option<&str>,
        managed: &BTreeMap<String, String>,
    ) {
        for (dir, kind) in [
            ("agents", ItemKind::Agent),
            ("rules", ItemKind::Rule),
            ("commands", ItemKind::Command),
        ] {
            let mut files = Vec::new();
            self.files(&base.join(dir), 0, &mut files);
            for path in files {
                let Some(rel) = rel_path(base, &path) else {
                    continue;
                };
                if !rel.ends_with(".md") {
                    continue;
                }
                let name = stem(&path);
                self.add(base, &rel, shown, source, plugin, kind, name, managed);
            }
        }
        let skills = base.join("skills");
        let mut dirs: Vec<_> = std::fs::read_dir(&skills)
            .into_iter()
            .flatten()
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.symlink_metadata().is_ok_and(|m| m.is_dir()) || p.is_symlink())
            .collect();
        dirs.sort();
        for dir in dirs {
            let name = dir
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_default();
            let mut files = Vec::new();
            if dir.is_symlink() {
                files.push(dir.clone());
            } else {
                self.files(&dir, 0, &mut files);
            }
            for path in files {
                let Some(rel) = rel_path(base, &path) else {
                    continue;
                };
                let kind = if rel == format!("skills/{name}/SKILL.md") {
                    ItemKind::Skill
                } else {
                    ItemKind::SkillFile
                };
                self.add(
                    base,
                    &rel,
                    shown,
                    source,
                    plugin,
                    kind,
                    name.clone(),
                    managed,
                );
            }
        }
    }

    /// Every file under `dir`, symlinks included but not followed.
    fn files(&mut self, dir: &Path, depth: usize, out: &mut Vec<std::path::PathBuf>) {
        if depth > MAX_DEPTH {
            self.truncated = true;
            return;
        }
        let mut entries: Vec<_> = std::fs::read_dir(dir)
            .into_iter()
            .flatten()
            .flatten()
            .map(|e| e.path())
            .collect();
        entries.sort();
        for path in entries {
            if self.items.len() + out.len() >= MAX_FILES {
                self.truncated = true;
                return;
            }
            match path.symlink_metadata() {
                Ok(m) if m.is_dir() => self.files(&path, depth + 1, out),
                Ok(_) => out.push(path),
                Err(_) => {}
            }
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn add(
        &mut self,
        base: &Path,
        rel: &str,
        shown: &str,
        source: Source,
        plugin: Option<&str>,
        kind: ItemKind,
        name: String,
        managed: &BTreeMap<String, String>,
    ) {
        let path = format!("{shown}/{rel}");
        let mut item = Item {
            source,
            plugin: plugin.map(str::to_string),
            kind,
            name,
            managed: source == Source::Project && managed.contains_key(&path),
            path,
            sha256: None,
            scan: Coverage::Pass,
            findings: Vec::new(),
            phrases: Vec::new(),
            links: Vec::new(),
        };
        scan_file(&base.join(rel), &mut item);
        self.items.push(item);
    }
}

/// Fingerprints and scans one file into `item`.
fn scan_file(path: &Path, item: &mut Item) {
    let incomplete = |item: &mut Item, why: &str| {
        item.scan = item.scan.max(Coverage::Incomplete);
        item.findings.push(why.to_string());
    };
    let meta = match path.symlink_metadata() {
        Ok(m) => m,
        Err(e) => return incomplete(item, &format!("can't be read ({e})")),
    };
    if meta.file_type().is_symlink() {
        return incomplete(item, "a symlink, not followed");
    }
    if !meta.is_file() {
        return incomplete(item, "not a regular file");
    }
    if meta.len() > MAX_BYTES {
        return incomplete(item, "over 1 MiB, not scanned");
    }
    let bytes = match std::fs::read(path) {
        Ok(b) => b,
        Err(e) => return incomplete(item, &format!("can't be read ({e})")),
    };
    let Ok(text) = String::from_utf8(bytes.clone()) else {
        item.sha256 = Some(format!("sha256:{}", mezha_broker::sha256_hex(&bytes)));
        return incomplete(item, "not text (a binary, archive or image), not scanned");
    };
    item.sha256 = Some(fingerprint(&text));
    for f in scan::body_findings(&text, item.runs_at_load()) {
        if f.what == EXTERNAL_REFERENCE && !f.encoded {
            let host = scan::link_host(&text[f.start..f.end]).to_ascii_lowercase();
            if !item.links.contains(&host) {
                item.links.push(host);
            }
            continue;
        }
        let at = format!("line {}: {} ({})", f.line, f.what, f.excerpt(&text));
        match f.level {
            Level::Hard | Level::Phi => {
                item.scan = Coverage::Fail;
                item.findings.push(at);
            }
            Level::Phrase if f.what == UNSCANNED => incomplete(item, &at),
            Level::Phrase => item.phrases.push(at),
        }
    }
}

/// Plugins `enabledPlugins` turns on, as `name@marketplace`: for each key,
/// the most specific settings file that names it decides.
pub fn enabled_plugins(layers: &Layers) -> Vec<String> {
    let mut state: BTreeMap<String, bool> = BTreeMap::new();
    for (value, _) in layers.every("/enabledPlugins") {
        for (id, on) in value.as_object().into_iter().flatten() {
            state.insert(id.clone(), on.as_bool() == Some(true));
        }
    }
    state
        .into_iter()
        .filter_map(|(id, on)| on.then_some(id))
        .collect()
}

/// Where Claude Code keeps an installed plugin: the `installPath` that
/// `installed_plugins.json` records for it, or else the newest version
/// under `cache/<marketplace>/<plugin>/`.
fn plugin_dir(plugins: &Path, id: &str) -> Option<PathBuf> {
    let recorded = std::fs::read_to_string(plugins.join("installed_plugins.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<Value>(&t).ok())
        .and_then(|v| {
            let entry = v
                .pointer("/plugins")
                .and_then(|p| p.get(id))
                .or_else(|| v.get(id))?
                .clone();
            let entries = match entry {
                Value::Array(list) => list,
                other => vec![other],
            };
            entries
                .iter()
                .rev()
                .find_map(|e| e.get("installPath")?.as_str().map(PathBuf::from))
        });
    if let Some(dir) = recorded.filter(|d| d.is_dir()) {
        return Some(dir);
    }
    let (name, marketplace) = id.split_once('@')?;
    let mut versions: Vec<PathBuf> =
        std::fs::read_dir(plugins.join("cache").join(marketplace).join(name))
            .ok()?
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.is_dir())
            .collect();
    versions.sort();
    versions.pop()
}

fn rel_path(base: &Path, path: &Path) -> Option<String> {
    let rel = path.strip_prefix(base).ok()?;
    let parts: Vec<String> = rel
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect();
    Some(parts.join("/"))
}

fn stem(path: &Path) -> String {
    path.file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_default()
}
